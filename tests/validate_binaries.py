"""Offline configuration checks with real binaries; no services started, no network.

XRAY_BINARY is required. NGINX_BINARY is optional locally and mandatory in CI.
This does not claim that a client connection or a Panel subscription was tested.
"""
import base64
import datetime
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cryptography import x509
from cryptography.hazmat.primitives import serialization, hashes
from cryptography.hazmat.primitives.asymmetric import rsa, x25519
from cryptography.x509.oid import NameOID
from egames_safe import add_routes, pq_pair
from remnawave_injector import build_inbound


def check(args, data=None):
    r = subprocess.run(args, input=data, text=True, capture_output=True, timeout=30)
    if r.returncode:
        # These are synthetic test credentials; print validator output to help diagnose.
        print(r.stdout, r.stderr)
        raise SystemExit(f"Validation failed: {args[0]}")
    return r.stdout


core = os.environ.get("XRAY_BINARY")
if not core:
    raise SystemExit("Set XRAY_BINARY to a verified official Xray executable")
print(check([core, "version"]).splitlines()[0])
with tempfile.TemporaryDirectory(prefix="egames-validation-") as directory:
    tmp = Path(directory)
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "node.example.com")])
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(subject).issuer_name(subject).public_key(key.public_key())
        .serial_number(x509.random_serial_number()).not_valid_before(now - datetime.timedelta(days=1))
        .not_valid_after(now + datetime.timedelta(days=1)).add_extension(
        x509.SubjectAlternativeName([x509.DNSName("node.example.com")]), critical=False).sign(key, hashes.SHA256()))
    certfile, keyfile = tmp / "cert.pem", tmp / "key.pem"
    certfile.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    keyfile.write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
    private = x25519.X25519PrivateKey.generate()
    private_b64 = base64.urlsafe_b64encode(private.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw, serialization.NoEncryption())).decode().rstrip("=")
    d, encryption = pq_pair(check([core, "vlessenc"]))
    definitions = [("VISION", "vless", "raw", "reality"), ("WS", "vless", "ws", "none"),
        ("XHTTP", "vless", "xhttp", "none"), ("XREALITY", "vless", "xhttp", "reality"),
        ("PQ", "vless", "raw", "reality"), ("GRPC", "trojan", "grpc", "none"),
        ("SS", "shadowsocks", "raw", "none"), ("HY2", "hysteria", "hysteria", "tls")]
    for idx, (tag, proto, net, sec) in enumerate(definitions):
        spec = dict(tag=tag, protocol=proto, network=net, security=sec, port=20000 + idx,
            path="/egadd/" + "a" * 24 + "/", service_name="egadd" + "b" * 24)
        if tag == "VISION":
            spec["flow"] = "xtls-rprx-vision"
        if tag == "PQ":
            spec.update(decryption=d, flow="")
        ib = build_inbound(spec, reality_private_key=private_b64, reality_short_id="0123456789abcdef",
            reality_server_name="node.example.com", reality_dest="127.0.0.1:18443",
            tls_cert_file=str(certfile), tls_key_file=str(keyfile))
        user = {"id": "11111111-1111-4111-8111-111111111111"}
        if proto == "vless":
            user["flow"] = spec.get("flow", "")
        if proto == "trojan":
            user = {"password": "synthetic-test-password"}
        if proto == "shadowsocks":
            user = {"password": base64.b64encode(b"u" * 32).decode()}
        if proto == "hysteria":
            user = {"auth": "synthetic-test-auth"}
        ib["settings"]["clients"] = [user]
        config = {"inbounds": [ib], "outbounds": [{"protocol": "freedom"}]}
        check([core, "run", "-test", "-config", "stdin:"], json.dumps(config))
        print(f"Xray server validation passed: {tag}")
    # The public frontend is TLS even though the backend inbound is cleartext.
    # Validate a PQ client encryption string generated by the same binary.
    client = {"outbounds": [{"protocol": "vless", "settings": {"vnext": [{"address": "127.0.0.1",
        "port": 23456, "users": [{"id": "11111111-1111-4111-8111-111111111111", "encryption": encryption}]}]},
        "streamSettings": {"network": "raw", "security": "tls", "tlsSettings": {"serverName": "node.example.com"}}}]}
    check([core, "run", "-test", "-config", "stdin:"], json.dumps(client))
    print("Xray PQ client encryption validation passed")
    nginx = os.environ.get("NGINX_BINARY")
    if nginx:
        original = (Path(__file__).parent / "fixtures/nginx.conf").read_text()
        modified = add_routes(original, "node.example.com", [
            {"path": "/egadd/" + "a" * 24 + "/", "port": 20001, "network": "ws"},
            {"path": "/egadd/" + "b" * 24 + "/", "port": 20002, "network": "xhttp"},
            {"path": "/egadd" + "c" * 24 + "/", "port": 20003, "network": "grpc"}])
        modified = modified.replace("/etc/nginx/ssl/example/fullchain.pem", certfile.as_posix()).replace(
            "/etc/nginx/ssl/example/privkey.pem", keyfile.as_posix())
        if os.name == "nt":
            modified = modified.replace("unix:/dev/shm/nginx.sock", "127.0.0.1:18443")
        else:
            modified = modified.replace("unix:/dev/shm/nginx.sock", "unix:" + (tmp / "nginx.sock").as_posix())
        (tmp / "logs").mkdir()
        (tmp / "temp").mkdir()
        full = 'events {}\nhttp {\n' + modified + '\n}\n'
        configfile = tmp / "nginx.conf"
        configfile.write_text(full)
        check([nginx, "-t", "-p", tmp.as_posix() + "/", "-c", str(configfile)])
        print("Nginx TLS + WS/XHTTP/gRPC route validation passed")
    else:
        print("SKIP Nginx binary validation: NGINX_BINARY not set")
